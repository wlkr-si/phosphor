/** One lit pixel of a title: its place in the title's own grid (column, row). */
export interface Pixel {
  col: number;
  row: number;
}

/** The lit pixels of `text` in the 5 x 7 alphabet, letters one pixel apart. */
export function pixels(text: string): { pixels: Pixel[]; cols: number; rows: number } {
  const out: Pixel[] = [];
  let x = 0;
  for (const [i, ch] of [...text.toUpperCase()].entries()) {
    if (i > 0) x += 1;
    const g = GLYPHS[ch] ?? GLYPHS[" "]!;
    g.forEach((line, row) => [...line].forEach((c, col) => c === "#" && out.push({ col: x + col, row })));
    x += 5;
  }
  return { pixels: out, cols: x, rows: 7 };
}
